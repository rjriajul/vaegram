"""Write tools/botapi/botapi.txt, the list of Bot API methods and types, from https://core.telegram.org/bots/api.

usage: python tools/botapi/scrape.py [saved.html]
"""
import html
import pathlib
import re
import sys
import urllib.request

URL = "https://core.telegram.org/bots/api"
OUT = pathlib.Path(__file__).with_name("botapi.txt")

page = (pathlib.Path(sys.argv[1]).read_text("utf-8") if len(sys.argv) > 1
        else urllib.request.urlopen(URL, timeout=60).read().decode())

version = re.search(r"<p><strong>(Bot API [\d.]+)</strong></p>", page)[1]
date = re.search(r'<h3>.*?Recent changes</h3>.*?<h4>.*?</a>(.*?)</h4>', page, re.S)[1]

sections, section = {}, []
for level, title in re.findall(r"<h([34])>.*?</a>(.*?)</h\1>", page):
    title = html.unescape(title)
    if level == "3":
        section = sections.setdefault(title, [])
    elif re.fullmatch(r"[a-z][A-Za-z0-9]+", title):
        section.append(f"method {title}")
    elif re.fullmatch(r"[A-Z][A-Za-z0-9]+", title):
        section.append(f"type {title}")

text = f"# {version}, {date}: generated by tools/botapi/scrape.py from {URL}\n"
text += "".join(f"\n## {name}\n" + "".join(f"{i}\n" for i in items) for name, items in sections.items() if items)
OUT.write_text(text, "utf-8", newline="\n")
count = lambda kind: sum(i.startswith(kind) for items in sections.values() for i in items)
print(f"{version}: {count('method ')} methods, {count('type ')} types -> {OUT}")
